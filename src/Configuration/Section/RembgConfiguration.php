<?php

namespace Photobooth\Configuration\Section;

use Symfony\Component\Config\Definition\Builder\NodeDefinition;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;

final class RembgConfiguration
{
    public static function getNode(): NodeDefinition
    {
        return (new TreeBuilder('rembg'))->getRootNode()->addDefaultsIfNotSet()
            ->ignoreExtraKeys()
            ->children()
                ->booleanNode('enabled')->defaultValue(false)->end()
                ->booleanNode('auto_apply')->defaultValue(false)->end()
                ->scalarNode('background')->defaultValue('')->end()
                ->enumNode('backgroundMode')
                    ->values(['none', 'scale-fit', 'scale-fill', 'crop-center', 'stretch'])
                    ->defaultValue('scale-fill')
                    ->end()
                ->enumNode('model')
                    ->values(['birefnet-portrait', 'rmbg-2.0', 'u2net', 'u2netp', 'u2net_cloth_seg', 'u2net_human_seg', 'silueta', 'isnet_general_use', 'isnet_anime', 'bria-rmbg'])
                    ->defaultValue('birefnet-portrait')
                    ->end()
                ->booleanNode('alpha_matting')->defaultValue(true)->end()
                ->integerNode('alpha_matting_foreground_threshold')
                    ->defaultValue(240)
                    ->min(0)
                    ->max(255)
                    ->beforeNormalization()
                        ->ifString()
                        ->then(function (string $value): int {
                            return intval($value);
                        })
                        ->end()
                    ->end()
                ->integerNode('alpha_matting_background_threshold')
                    ->defaultValue(10)
                    ->min(0)
                    ->max(255)
                    ->beforeNormalization()
                        ->ifString()
                        ->then(function (string $value): int {
                            return intval($value);
                        })
                        ->end()
                    ->end()
                ->integerNode('alpha_matting_erode_size')
                    ->defaultValue(10)
                    ->min(0)
                    ->max(255)
                    ->beforeNormalization()
                        ->ifString()
                        ->then(function (string $value): int {
                            return intval($value);
                        })
                        ->end()
                    ->end()
                ->booleanNode('post_processing')->defaultValue(false)->end()
                ->enumNode('engine')
                    ->values(['birefnet', 'rmbg2', 'rembg', 'feynobg'])
                    ->defaultValue('birefnet')
                    ->end()
                ->enumNode('gpu_mode')
                    ->values(['auto', 'cuda', 'directml', 'cpu', 'gpu'])
                    ->defaultValue('auto')
                    ->end()
                ->integerNode('cpu_threads')
                    ->defaultValue(4)
                    ->min(1)
                    ->max(32)
                    ->end()
                ->booleanNode('auto_fallback')->defaultValue(true)->end()
                ->enumNode('quality_preset')
                    ->values(['speed', 'balanced', 'quality', 'hair', 'custom'])
                    ->defaultValue('balanced')
                    ->end()
                ->integerNode('max_input_size')
                    ->defaultValue(1920)
                    ->min(512)
                    ->max(4096)
                    ->end()
                ->booleanNode('postprocess_enabled')->defaultValue(true)->end()
                ->integerNode('defringe_radius')
                    ->defaultValue(1)
                    ->min(0)
                    ->max(4)
                    ->end()
                ->booleanNode('preserve_hair')->defaultValue(true)->end()
                ->booleanNode('quality_check_enabled')->defaultValue(true)->end()
                ->booleanNode('quality_retry')->defaultValue(true)->end()
                ->integerNode('quality_max_retries')
                    ->defaultValue(2)
                    ->min(0)
                    ->max(3)
                    ->end()
                ->booleanNode('animation_enabled')->defaultValue(true)->end()
                ->enumNode('animation_style')
                    ->values(['simple', 'neon', 'laser', 'advanced'])
                    ->defaultValue('laser')
                    ->end()
                ->integerNode('animation_duration')
                    ->defaultValue(1200)
                    ->min(100)
                    ->max(5000)
                    ->end()
                ->integerNode('animation_line_width')
                    ->defaultValue(2)
                    ->min(1)
                    ->max(8)
                    ->end()
                ->booleanNode('animation_adaptive_quality')->defaultValue(true)->end()
                ->booleanNode('cache_enabled')->defaultValue(true)->end()
                ->integerNode('cache_max_age_days')
                    ->defaultValue(7)
                    ->min(0)
                    ->max(365)
                    ->end()
                ->integerNode('cache_max_size_mb')
                    ->defaultValue(2048)
                    ->min(64)
                    ->max(16384)
                    ->end()
            ->end();
    }
}
